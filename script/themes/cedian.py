"""Color tokens (Warm & Lime), written out for the window as src/theme/tokens.ts.

The TOKENS table is the color source of truth. src/theme/theme.ts maps the tokens to
VS Code's color ids (the workbench theme) and to --cedian-* CSS custom properties
(the agent pane and Cedian's other blocks); docs/VENDORING.md step 8.

Run from the repository root: npm run theme (src/theme/theme.test.ts fails when
tokens.ts is stale). Change a token here and in the spec's table together.
"""

