out = pathlib.Path("src/theme/tokens.ts")
out.parent.mkdir(parents=True, exist_ok=True)
body = json.dumps(TOKENS, indent=2)
out.write_text(
    "// Generated by script/themes/cedian.py from its TOKENS table. Do not edit.\n"
    f"export const TOKENS = {body} as const;\n\n"
    "export type Appearance = keyof typeof TOKENS;\n"
    "export type Token = keyof (typeof TOKENS)[\"dark\"];\n"
)
print(out)
