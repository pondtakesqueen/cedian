#!/usr/bin/env node
// Generates src/protocol/cedia.ts from the one pinned schema,
// daemon/crates/cedian_protocol/cedia/protocol.schema.json, so the window's types follow
// the same cedia revision as the daemon's (`script/pin-cedia` moves both), and
// src/protocol/wire.ts from the daemon's own wire schema, daemon/crates/cedian_wire/wire.schema.json
// (`CEDIAN_UPDATE_SCHEMA=1 cargo test -p cedian_wire` writes it from the Rust types).
// Usage: node script/protocol-types.mjs [--check]
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { compile } from "json-schema-to-typescript";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const schemaPath = join(root, "daemon/crates/cedian_protocol/cedia/protocol.schema.json");
const outPath = join(root, "src/protocol/cedia.ts");
const wireSchemaPath = join(root, "daemon/crates/cedian_wire/wire.schema.json");
const wireOutPath = join(root, "src/protocol/wire.ts");

export async function generate() {
  const rev = readFileSync(join(root, "daemon/crates/cedian_protocol/cedia/REV"), "utf8").trim();
  return compileRoots(schemaPath, "CediaRoots", `// Generated by script/protocol-types.mjs from cedia ${rev}. Do not edit.`);
}

export async function generateWire() {
  return compileRoots(wireSchemaPath, "WireRoots", "// Generated by script/protocol-types.mjs from daemon/crates/cedian_wire/wire.schema.json. Do not edit.");
}

async function compileRoots(path, title, bannerComment) {
  const schema = JSON.parse(readFileSync(path, "utf8"));
  // The schema's top level only names its roots; every definition is a type of its own.
  const body = await compile(
    { $schema: schema.$schema, title, definitions: schema.definitions, type: "object", properties: schema.roots, additionalProperties: false },
    title,
    {
      bannerComment,
      unreachableDefinitions: true,
      additionalProperties: false,
      strictIndexSignatures: true,
      format: true,
      style: { printWidth: 100 },
    },
  );
  return body;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  for (const [out, body] of [[outPath, await generate()], [wireOutPath, await generateWire()]]) {
    if (process.argv.includes("--check")) {
      if (readFileSync(out, "utf8") !== body) {
        console.error(`${out} is stale; run node script/protocol-types.mjs`);
        process.exit(1);
      }
    } else {
      writeFileSync(out, body);
      console.log(`wrote ${out}`);
    }
  }
}
