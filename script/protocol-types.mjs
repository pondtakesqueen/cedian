#!/usr/bin/env node
// Generates src/protocol/cedia.ts from the one pinned schema,
// daemon/crates/cedian_protocol/cedia/protocol.schema.json, so the window's types follow
// the same cedia revision as the daemon's (`script/pin-cedia` moves both).
// Usage: node script/protocol-types.mjs [--check]
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { compile } from "json-schema-to-typescript";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const schemaPath = join(root, "daemon/crates/cedian_protocol/cedia/protocol.schema.json");
const outPath = join(root, "src/protocol/cedia.ts");

export async function generate() {
  const schema = JSON.parse(readFileSync(schemaPath, "utf8"));
  const rev = readFileSync(join(root, "daemon/crates/cedian_protocol/cedia/REV"), "utf8").trim();
  // The schema's top level only names its roots; every definition is a type of its own.
  const body = await compile(
    { $schema: schema.$schema, title: "CediaRoots", definitions: schema.definitions, type: "object", properties: schema.roots, additionalProperties: false },
    "CediaRoots",
    {
      bannerComment: `// Generated by script/protocol-types.mjs from cedia ${rev}. Do not edit.`,
      unreachableDefinitions: true,
      additionalProperties: false,
      strictIndexSignatures: true,
      format: true,
      style: { printWidth: 100 },
    },
  );
  return body;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const body = await generate();
  if (process.argv.includes("--check")) {
    if (readFileSync(outPath, "utf8") !== body) {
      console.error("src/protocol/cedia.ts is stale; run node script/protocol-types.mjs");
      process.exit(1);
    }
  } else {
    writeFileSync(outPath, body);
    console.log(`wrote ${outPath}`);
  }
}
